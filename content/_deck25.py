"""The eight Instagram carousels, rebuilt on the approved 2.5D working model.

Themes and copy carry over from the decks the operator kept; what changes is the machinery
underneath. Every slide is now header / STAGE / caption / footer against a declared pixel
workspace (CLAUDE.md 30), and the scene is built to fill the stage rather than sized to itself
and centred in the leftovers.

The three binding content rules are unchanged and still enforced by reading, not by hope:

1. FAST REWARD. The clock is 24 to 72 hours, never a month. Thirty days is a plan.
2. NO AGENT NAMES, EVER, and no internal mechanics as headlines. Plain words only.
3. GAIN, NOT AVOIDANCE. Become, launch, first customer, wake up shipped, revenue.

Graphic variety is asserted from what actually gets built: each scene stamps `data-ob` on its
own root, the run is read back off the slides, and the build fails on a repeat inside a deck,
a duplicate run, or two decks opening on the same form.
"""
