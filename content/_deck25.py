DECKS = []


def D(slug, title, kw, slides):
    DECKS.append(dict(slug=slug, title=title, kw=kw, slides=slides,
                      run=[re.search(r'data-ob="([a-z0-9]+)"', s["scene"]).group(1)
                           for s in slides]))


def S(eyebrow, h, sub, scene, cap=None):
    return dict(eyebrow=eyebrow, h=h, sub=sub, scene=scene, cap=cap)


